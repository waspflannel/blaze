"""Verilator block simulation, compared bit for bit against the Python integer reference.

Verilator runs natively when it is on PATH. On Windows without it, it runs inside WSL from
OSS CAD Suite unpacked at ~/tools/oss-cad-suite (see README). Deterministic; no LLM involved.
"""
import os
import re
import shlex
import shutil
import subprocess
from pathlib import Path

import numpy as np

from blaze.generate import acc_width, quantize
from blaze.library import BUILDERS, Block, Port, build_op, random_inputs
from blaze.reference import matvec_int
from blaze.spec import load_matrix

WSL_TOOLS = "$HOME/tools/oss-cad-suite/bin"
MATMUL_TENSORS = ["wq", "wk", "wv", "wo", "w1", "w2", "w3"]


def reference_block(checkpoint: Path, ref: str, bits: int = 8) -> Block:
    """Block for a ref id `layer<N>.<matmul tensor or op>`, e.g. layer0.wq or layer0.rmsnorm.

    `bits` is the matmul weight width gen-matrix used; ops ignore it.
    """
    m = re.fullmatch(r"layer(\d+)\.(\w+)", ref)
    if not m:
        raise ValueError(f"bad --ref {ref!r}; expected layer<N>.<name>, e.g. layer0.wq")
    layer, name = int(m[1]), m[2]
    if name in MATMUL_TENSORS:
        q, _ = quantize(load_matrix(checkpoint, layer, name), bits)
        rows, cols = q.shape
        return Block([Port("x", cols, 8)], Port("y", rows, acc_width(q)), lambda v: matvec_int(q, v["x"]))
    if name in BUILDERS:
        return build_op(checkpoint, layer, name, f"l{layer}_{name}")
    raise ValueError(f"unknown ref name {name!r}; expected one of {', '.join(MATMUL_TENSORS + list(BUILDERS))}")


def module_ports(text: str, top: str) -> dict[str, tuple[str, int]]:
    """{port: (direction, width)} of an ANSI-style module header."""
    m = re.search(rf"\bmodule\s+{re.escape(top)}\b[^(]*\((.*?)\);", text, re.S)
    if not m:
        raise ValueError(f"no module {top!r} in the file (the top module must match the file name)")
    ports = {}
    for d, msb, name in re.findall(r"\b(input|output)\s+(?:wire\s+)?(?:\[(\d+):0\]\s*)?(\w+)", m[1]):
        ports[name] = (d, int(msb) + 1 if msb else 1)
    return ports


def _command(args: list[str]) -> list[str]:
    if shutil.which("verilator"):
        return args
    if os.name == "nt" and shutil.which("wsl"):
        return ["wsl", "-e", "bash", "-c", f'PATH="{WSL_TOOLS}:$PATH"; {shlex.join(args)}']
    raise RuntimeError("verilator not found; see README, Simulation setup")


def _run(args: list[str], cwd: Path, stdin: str | None = None) -> str:
    r = subprocess.run(_command(args), cwd=cwd, input=stdin, capture_output=True, text=True)
    if r.returncode:
        tail = "\n".join((r.stderr or r.stdout).strip().splitlines()[-15:])
        hint = "\n(verilator missing? see README, Simulation setup)" if r.returncode == 127 else ""
        raise RuntimeError(f"{args[0]} failed with exit {r.returncode}:\n{tail}{hint}")
    return r.stdout


TESTBENCH = """// Generated by blaze sim-block: one input vector per stdin line (hex per input port, MSB first),
// one output line per vector (hex per output port).
#include <cstdint>
#include <cstdio>
#include <iostream>
#include <memory>
#include <sstream>
#include <string>
#include <vector>
#include "verilated.h"
#include "V@TOP@.h"

static std::vector<uint32_t> parse_hex(const std::string& h, size_t words) {
    std::vector<uint32_t> w(words, 0);
    size_t end = h.size();
    for (size_t k = 0; k < words && end > 0; k++) {
        size_t start = end >= 8 ? end - 8 : 0;
        w[k] = (uint32_t)std::stoul(h.substr(start, end - start), nullptr, 16);
        end = start;
    }
    return w;
}

static void print_hex(const std::vector<uint32_t>& w) {
    for (size_t i = w.size(); i-- > 0;) std::printf("%08x", w[i]);
}

int main(int argc, char** argv) {
    auto ctx = std::make_unique<VerilatedContext>();
    ctx->commandArgs(argc, argv);
    auto top = std::make_unique<V@TOP@>(ctx.get());
    std::string line;
    while (std::getline(std::cin, line)) {
        std::istringstream in(line);
        std::string tok;
@SET@
        top->eval();
@GET@
        std::printf("\\n");
    }
    top->final();
    return 0;
}
"""


def _testbench(top: str, inputs: list[Port], output: Port) -> str:
    set_lines = []
    for p in inputs:
        n = (p.width + 31) // 32
        set_lines.append(f"        in >> tok; {{ auto w = parse_hex(tok, {n});")
        if p.width > 64:
            set_lines.append(f"          for (size_t i = 0; i < {n}; i++) top->{p.name}[i] = w[i]; }}")
        elif p.width > 32:
            set_lines.append(f"          top->{p.name} = ((uint64_t)w[1] << 32) | w[0]; }}")
        else:
            set_lines.append(f"          top->{p.name} = w[0]; }}")
    n = (output.width + 31) // 32
    o = output.name
    if output.width > 64:
        get = f"        {{ std::vector<uint32_t> w({n}); for (size_t i = 0; i < {n}; i++) w[i] = top->{o}[i]; print_hex(w); }}"
    elif output.width > 32:
        get = f"        print_hex({{(uint32_t)top->{o}, (uint32_t)(top->{o} >> 32)}});"
    else:
        get = f"        print_hex({{(uint32_t)top->{o}}});"
    return TESTBENCH.replace("@TOP@", top).replace("@SET@", "\n".join(set_lines)).replace("@GET@", get)


def _pack(values: np.ndarray, bits: int) -> int:
    mask = (1 << bits) - 1
    packed = 0
    for i, v in enumerate(values):
        packed |= (int(v) & mask) << (bits * i)
    return packed


def _unpack(packed: int, port: Port) -> list[int]:
    mask, sign = (1 << port.bits) - 1, 1 << (port.bits - 1)
    out = []
    for i in range(port.count):
        v = (packed >> (port.bits * i)) & mask
        out.append(v - (1 << port.bits) if v & sign else v)
    return out


def simulate(verilog: Path, block: Block, vectors: int, seed: int, workdir: Path) -> dict:
    """Compile `verilog` with Verilator, drive seeded vectors, compare every output with the reference."""
    top = verilog.stem
    text = verilog.read_text()
    ports = module_ports(text, top)
    expected = {p.name: ("input", p.width) for p in block.inputs}
    expected[block.output.name] = ("output", block.output.width)
    if ports != expected:
        raise ValueError(f"{verilog} ports {ports} do not match the reference's {expected}")

    workdir.mkdir(parents=True, exist_ok=True)
    (workdir / f"{top}.v").write_text(text, newline="\n")
    (workdir / "tb.cpp").write_text(_testbench(top, block.inputs, block.output), newline="\n")
    version = _run(["verilator", "--version"], workdir).strip()
    _run(["verilator", "--cc", "--exe", "--build", "-j", "0", "-Wno-fatal", "--top-module", top,
          "-Mdir", "obj", "-o", "Vsim", f"{top}.v", "tb.cpp"], workdir)

    inputs = random_inputs(block.inputs, vectors, seed)
    stdin = "".join(" ".join(f"{_pack(v[p.name], p.bits):x}" for p in block.inputs) + "\n" for v in inputs)
    lines = _run(["./obj/Vsim"], workdir, stdin).split()
    if len(lines) != vectors:
        raise RuntimeError(f"simulator returned {len(lines)} vectors, expected {vectors}")

    first = None
    bad = 0
    for i, (v, line) in enumerate(zip(inputs, lines)):
        got = _unpack(int(line, 16), block.output)
        want = [int(e) for e in block.reference(v)]
        if got != want:
            bad += 1
            if first is None:
                k = next(k for k, (g, w) in enumerate(zip(got, want)) if g != w)
                first = {"vector": i, "element": k, "expected": want[k], "got": got[k]}
    return {"file": str(verilog), "top": top, "simulator": version, "vectors": vectors, "seed": seed,
            "outputs_per_vector": block.output.count, "match": bad == 0, "mismatched_vectors": bad,
            "first_mismatch": first}
