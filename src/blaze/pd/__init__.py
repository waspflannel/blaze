"""Physical design of one compiled layer (or one block) with OpenLane 2 on SKY130 (sky130_fd_sc_hd).

`run_pd` writes a shift-chain wrapper top around the layer's generated blocks, an OpenLane 2 config.json,
then checks the toolchain and free memory, runs `openlane` and maps its final/metrics.json into pd.json.
Every metric is {"value", "unit", "source": "measured|estimated|unavailable", "from"}; blaze never computes one.
OpenLane runs natively when on PATH, else in WSL on Windows (same pattern as sim-block). Nothing is installed.
"""
import datetime
import hashlib
import json
import os
import platform
import posixpath
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

from blaze.sim import WSL_TOOLS, module_ports

REPO = Path(__file__).resolve().parents[3]
TOOLS = ["openlane", "openroad", "magic", "netgen", "klayout", "yosys"]
PDK, SCL = "sky130A", "sky130_fd_sc_hd"
PDK_DIRS = ["$PDK_ROOT", "$HOME/.ciel", "$HOME/.volare"]
TOOL_PATH = f"{WSL_TOOLS}:$HOME/.local/bin"
# OpenROAD's report_power with no VCD/SAIF: OpenSTA's default input activity, propagated through the logic.
ACTIVITY = "OpenSTA default activity (no VCD/SAIF annotation); vectorless, not a workload measurement"


def _blocks(layer_dir: Path) -> list[Path]:
    """Every block of the layer, the .opt.v of a matvec in place of its .v."""
    plain = sorted(p for p in layer_dir.glob("*.v") if not p.name.endswith(".opt.v"))
    picked = [p.with_name(p.stem + ".opt.v") if p.with_name(p.stem + ".opt.v").exists() else p for p in plain]
    if not picked:
        raise ValueError(f"no generated .v blocks in {layer_dir}")
    return picked


def _top(path: Path) -> str:
    return path.name.removesuffix(".v").removesuffix(".opt")


def wrap(blocks: list[Path], top: str, out: Path) -> dict:
    """Write `top`.v: a shift-in chain feeds every block input from registers, `capture` registers every block
    output into a shift-out chain. Keeps all real logic observable behind 6 pins; timing is reg-to-reg."""
    ins, outs, inst = [], [], []
    for b in blocks:
        name = _top(b)
        ports = module_ports(b.read_text(), name)
        conns = []
        for p, (d, w) in ports.items():
            (ins if d == "input" else outs).append((f"{name}_{p}", w))
            conns.append(f".{p}({name}_{p})")
        inst.append(f"    {name} u_{name} ({', '.join(conns)});")
    ni, no = sum(w for _, w in ins), sum(w for _, w in outs)
    lines = [f"// Generated by blaze pd: shift-chain wrapper around {len(blocks)} block(s); not functional I/O.",
             "`default_nettype none", f"module {top} (",
             "    input  wire clk, rst_n, si, shift_en, capture,", "    output wire so", ");",
             f"    reg [{ni - 1}:0] in_sr;", f"    reg [{no - 1}:0] out_sr;"]
    lines += [f"    wire [{w - 1}:0] {n};" for n, w in ins + outs]
    lo = 0
    for n, w in ins:
        lines.append(f"    assign {n} = in_sr[{lo + w - 1}:{lo}];")
        lo += w
    cat = ", ".join(n for n, _ in reversed(outs))
    lines += inst + [
        "    always @(posedge clk) begin",
        f"        if (!rst_n) begin in_sr <= {ni}'d0; out_sr <= {no}'d0; end",
        "        else begin",
        f"            if (shift_en) in_sr <= {{in_sr[{ni - 2}:0], si}};" if ni > 1 else "            if (shift_en) in_sr <= si;",
        f"            if (capture) out_sr <= {{{cat}}};",
        f"            else if (shift_en) out_sr <= {{out_sr[{no - 2}:0], 1'b0}};" if no > 1 else
        "            else if (shift_en) out_sr <= 1'b0;",
        "        end", "    end", f"    assign so = out_sr[{no - 1}];", "endmodule", "`default_nettype wire", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), newline="\n")
    return {"file": str(out), "blocks": [_top(b) for b in blocks], "input_bits": ni, "output_bits": no,
            "wrapper_flops": ni + no}


def write_config(out_dir: Path, top: str, files: list[Path], clock_ns: float, threads: int) -> Path:
    """OpenLane 2 config.json; paths are dir:: relative so the same file works natively and from WSL."""
    rel = [f"dir::{Path(os.path.relpath(f, out_dir)).as_posix()}" for f in files]
    cfg = {"meta": {"version": 2, "flow": "Classic"}, "DESIGN_NAME": top, "VERILOG_FILES": rel,
           "CLOCK_PORT": "clk", "CLOCK_PERIOD": clock_ns,
           # Conservative: a big flat combinational design routes far easier at low density.
           "FP_CORE_UTIL": 35, "PL_TARGET_DENSITY_PCT": 45, "DRT_THREADS": threads}
    path = out_dir / "config.json"
    path.write_text(json.dumps(cfg, indent=2) + "\n", newline="\n")
    return path


def _shell(script: str) -> list[str] | None:
    """bash argv for a script: native, or inside WSL on Windows; None when neither exists."""
    if os.name == "nt":
        return ["wsl", "-e", "bash", "-c", script] if shutil.which("wsl") else None
    return ["bash", "-c", script] if shutil.which("bash") else None


PROBE = f"""export PATH="{TOOL_PATH}:$PATH"
for t in {' '.join(TOOLS)}; do echo "tool $t $(command -v $t)"; done
for d in {' '.join(f'"{d}"' for d in PDK_DIRS)}; do
  [ -n "$d" ] && [ -d "$d" ] && p=$(find "$d" -maxdepth 6 -name {PDK} 2>/dev/null | head -1) && [ -n "$p" ] && break
done
[ -n "$p" ] && echo "pdk $p" && [ -d "$p/libs.ref/{SCL}" ] && echo "scl $p/libs.ref/{SCL}"
echo "pdkroot ${{PDK_ROOT:-unset}}"
echo "ver openlane $(openlane --version 2>/dev/null | tail -1)"
echo "ver openroad $(openroad -version 2>/dev/null | head -1)"
echo "ver yosys $(yosys -V 2>/dev/null | head -1)"
echo "ver magic $(magic --version 2>/dev/null | head -1)"
echo "ver klayout $(klayout -v 2>/dev/null | head -1)"
echo "ver netgen $(netgen -batch quit 2>/dev/null | grep -m1 -i 'netgen ')"
echo "mem $(awk '/MemAvailable/ {{print $2}} /MemTotal/ {{print $2}}' /proc/meminfo | tr '\\n' ' ')"
echo "cpu $(nproc) $(cut -d' ' -f1 /proc/loadavg)"
"""


def preflight(max_mem_gb: float) -> dict:
    """Toolchain + PDK + resources. Returns blockers (exact items and what was checked) and resource numbers."""
    where = "WSL (wsl -e bash)" if os.name == "nt" else "bash"
    checked = f"`command -v` in {where} with PATH += {TOOL_PATH}"
    argv = _shell(PROBE)
    if argv is None:
        return {"blockers": [{"item": "wsl" if os.name == "nt" else "bash", "checked": "shutil.which"}],
                "tools": {}, "versions": {}, "resources": {}, "pdk": None}
    r = subprocess.run(argv, capture_output=True, text=True)
    tools, versions, pdk, scl, res, pdk_root = {}, {}, None, None, {}, "unset"
    for line in r.stdout.splitlines():
        kind, _, rest = line.partition(" ")
        if kind == "tool":
            name, _, path = rest.partition(" ")
            tools[name] = path.strip() or None
        elif kind == "pdk":
            pdk = rest.strip()
        elif kind == "scl":
            scl = rest.strip()
        elif kind == "pdkroot":
            pdk_root = rest.strip()
        elif kind == "ver":
            name, _, v = rest.partition(" ")
            versions[name] = v.strip() or None
        elif kind == "mem" and len(rest.split()) >= 2:  # /proc/meminfo order: MemTotal, MemAvailable (kB)
            total, avail = (int(x) for x in rest.split()[:2])
            res["flow_mem_total_gb"], res["flow_mem_free_gb"] = round(total / 2**20, 1), round(avail / 2**20, 1)
        elif kind == "cpu" and rest.split():
            n, load = rest.split()[:2]
            res["flow_cpus"], res["flow_load_1min"] = int(n), float(load)
    blockers = [{"item": t, "checked": checked} for t in TOOLS if not tools.get(t)]
    if pdk is None:
        blockers.append({"item": f"SKY130 PDK ({PDK})",
                         "checked": f"find -name {PDK} under {', '.join(PDK_DIRS)} in {where} (PDK_ROOT={pdk_root})"})
    elif scl is None:
        blockers.append({"item": f"std-cell library {SCL}", "checked": f"{pdk}/libs.ref/{SCL} in {where}"})
    res.update(_host_resources())
    free = [v for k, v in res.items() if k in ("flow_mem_free_gb", "host_mem_free_gb")]
    res["free_gb_used_for_check"] = min(free) if free else None
    res["max_mem_gb"] = max_mem_gb
    return {"blockers": blockers, "tools": tools, "versions": versions, "resources": res, "pdk": pdk,
            "probe_stderr": r.stderr.strip()[-500:] or None}


def _host_resources() -> dict:
    """Windows host free RAM and CPU load (WSL's memory comes out of it)."""
    if os.name != "nt":
        return {}
    ps = ("$o=Get-CimInstance Win32_OperatingSystem; $c=(Get-CimInstance Win32_Processor | "
          "Measure-Object LoadPercentage -Average).Average; \"$($o.FreePhysicalMemory) $($o.TotalVisibleMemorySize) $c\"")
    try:
        r = subprocess.run(["powershell", "-NoProfile", "-Command", ps], capture_output=True, text=True, timeout=60)
        free, total, load = r.stdout.split()[:3]
    except (OSError, ValueError, subprocess.TimeoutExpired):
        return {}
    return {"host_mem_free_gb": round(int(free) / 2**20, 1), "host_mem_total_gb": round(int(total) / 2**20, 1),
            "host_cpu_load_pct": float(load)}


def _metric(m: dict, key: str, unit: str, frm: str) -> dict:
    if key in m and m[key] is not None:
        return {"value": m[key], "unit": unit, "source": "measured", "from": f"{frm}:{key}"}
    return {"value": None, "unit": unit, "source": "unavailable", "from": f"{key} not in {frm}"}


def _missing(unit: str, reason: str) -> dict:
    return {"value": None, "unit": unit, "source": "unavailable", "from": reason}


METRICS = {  # pd.json group -> name -> (OpenLane 2 metrics.json key, unit)
    "area": {"die": ("design__die__area", "um^2"), "core": ("design__core__area", "um^2"),
             "stdcell": ("design__instance__area__stdcell", "um^2"),
             "cell_count": ("design__instance__count__stdcell", "cells"),
             "utilization": ("design__instance__utilization", "fraction")},
    "timing": {"wns": ("timing__setup__ws", "ns"), "tns": ("timing__setup__tns", "ns")},
    "power": {"internal": ("power__internal__total", "W"), "switching": ("power__switching__total", "W"),
              "leakage": ("power__leakage__total", "W"), "total": ("power__total", "W")},
    "drc": {"magic_violations": ("magic__drc_error__count", "count"),
            "klayout_violations": ("klayout__drc_error__count", "count")},
    "lvs": {"errors": ("design__lvs_error__count", "count")},
}


def collect(run_dir: Path | None) -> dict:
    """Map final/metrics.json (and resolved.json for the clock) into pd.json groups; nothing is computed."""
    mpath = run_dir / "final" / "metrics.json" if run_dir else None
    m = json.loads(mpath.read_text()) if mpath and mpath.exists() else None
    out = {}
    for group, items in METRICS.items():
        out[group] = {name: _metric(m, key, unit, str(mpath)) if m is not None else
                      _missing(unit, "no OpenLane run" if run_dir is None else f"{mpath} missing")
                      for name, (key, unit) in items.items()}
    resolved = run_dir / "resolved.json" if run_dir else None
    rc = json.loads(resolved.read_text()) if resolved and resolved.exists() else None
    out["timing"]["clock_period"] = (_metric(rc, "CLOCK_PERIOD", "ns", str(resolved)) if rc is not None
                                     else _missing("ns", "no resolved.json from an OpenLane run"))
    out["timing"]["corner"] = "worst of all STA corners (timing__setup__ws / __tns)"
    out["power"]["activity"] = ACTIVITY
    lvs = out["lvs"]["errors"]
    out["lvs"]["match"] = (lvs["value"] == 0) if lvs["source"] == "measured" else None
    return out


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _git(*args: str) -> str | None:
    try:
        return subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def provenance(inputs: list[Path], layer_dir: Path, pre: dict | None, threads: int, max_mem_gb: float) -> dict:
    pdk = (pre or {}).get("pdk")
    vh = re.search(r"/versions/([0-9a-f]+)/", pdk or "")
    dirty = _git("status", "--porcelain", "--untracked-files=no")
    versions = (pre or {}).get("versions", {})
    return {"blaze_git_sha": _git("rev-parse", "HEAD"), "blaze_git_dirty": None if dirty is None else bool(dirty),
            "inputs": [{"file": str(p), "sha256": _sha(p)} for p in inputs],
            "model": layer_dir.parent.name, "layer": layer_dir.name,
            "openlane_version": versions.get("openlane"), "pdk": PDK, "pdk_path": pdk,
            "pdk_version_hash": vh[1] if vh else None, "std_cell_lib": SCL,
            "tool_versions": {k: v for k, v in versions.items() if k != "openlane"},
            "threads": threads, "max_mem_gb": max_mem_gb, "command": [Path(sys.argv[0]).name, *sys.argv[1:]],
            "host_os": platform.platform()}


def _now() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")


def run_pd(layer_dir: Path, block: str | None, out: Path | None, clock_ns: float, threads: int | None,
           max_mem_gb: float, dry_run: bool) -> dict:
    """Wrap, configure, preflight, run, collect. Returns the pd.json dict (also written unless dry-run)."""
    start = _now()
    m = re.fullmatch(r"layer(\d+)", layer_dir.name)
    if not m or not layer_dir.is_dir():
        raise ValueError(f"{layer_dir} is not a build/<model>/layer<N>/ directory")
    if block:
        b = layer_dir / block
        if not b.exists():
            raise ValueError(f"no block {b}")
        blocks, target, scope = [b], _top(b), "block-substitute"
    else:
        blocks, target, scope = _blocks(layer_dir), layer_dir.name, "layer"
    out = out or layer_dir.parent / "pd" / target
    if block and not dry_run:
        layer_pd = layer_dir.parent / "pd" / layer_dir.name / "pd.json"
        prior = json.loads(layer_pd.read_text()).get("status") if layer_pd.exists() else None
        if prior not in ("deferred", "failed"):
            raise ValueError(f"--block is a substitute only after a layer run was deferred or failed for resources; "
                             f"{layer_pd} status is {prior or 'missing'}")
    top = f"l{m[1]}_pd_top" if not block else f"{target}_pd_top"
    w = wrap(blocks, top, out / f"{top}.v")
    pre = None if dry_run else preflight(max_mem_gb)
    cpus = (pre or {}).get("resources", {}).get("flow_cpus") or os.cpu_count() or 2
    threads = threads or max(1, min(4, cpus // 2))
    config = write_config(out, top, blocks + [Path(w["file"])], clock_ns, threads)
    r = {"status": None, "scope": scope, "target": target, "top": top, "out": str(out), "config": str(config),
         "wrapper": w, "gds": None, "run_dir": None, "blockers": [], "reason": None}
    run_dir = None
    if dry_run:
        r["status"], r["reason"] = "dry-run", "wrapper and config written; OpenLane not run"
    elif pre["blockers"]:
        r["status"], r["blockers"] = "blocked", pre["blockers"]
        r["reason"] = "toolchain/PDK missing: " + ", ".join(b["item"] for b in pre["blockers"])
    elif (pre["resources"].get("free_gb_used_for_check") or 0) < max_mem_gb:
        r["status"] = "deferred"
        r["reason"] = (f"free memory {pre['resources'].get('free_gb_used_for_check')} GB < --max-mem-gb {max_mem_gb}")
    else:
        tag = "blaze-" + datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
        run_dir = out / "runs" / tag
        # ponytail: ulimit -v caps address space, not RSS; a cgroup (systemd-run) cap is better where available.
        script = (f'export PATH="{TOOL_PATH}:$PATH"; ulimit -v {int(max_mem_gb * 2**20)}; '
                  f"openlane --manual-pdk --pdk-root {shlex.quote(posixpath.dirname(pre['pdk']))} --pdk {PDK} "
                  f"--scl {SCL} -j {threads} --run-tag {tag} config.json")
        (out / "runs").mkdir(parents=True, exist_ok=True)
        with open(out / "runs" / f"{tag}.log", "w") as log:
            code = subprocess.run(_shell(script), cwd=out, stdout=log, stderr=subprocess.STDOUT).returncode
        gds = sorted((run_dir / "final" / "gds").glob("*.gds"))
        r["run_dir"], r["gds"] = str(run_dir), str(gds[0]) if gds else None
        r["status"] = "complete" if code == 0 and gds else "failed"
        r["reason"] = None if r["status"] == "complete" else f"openlane exit {code}; log {out / 'runs' / f'{tag}.log'}"
    r["metrics"] = collect(run_dir)
    r["resources"] = (pre or {}).get("resources", {})
    r["provenance"] = provenance(blocks, layer_dir, pre, threads, max_mem_gb)
    r["provenance"].update({"start": start, "end": _now()})
    r["summary"] = (f"{r['status']}: {target}" + (" (substitute, not a layer result)" if block else "")
                    + (f" - {r['reason']}" if r["reason"] else ""))
    if not dry_run:
        (out / "pd.json").write_text(json.dumps(r, indent=2) + "\n", newline="\n")
        r["pd_json"] = str(out / "pd.json")
    return r
